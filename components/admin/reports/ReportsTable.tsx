'use client';

import React, { useState } from 'react';
import {
  Download,
  MoreHorizontal,
  CheckCircle2,
  Calendar,
  Clock,
  Play,
  Trash2,
  FileText,
  Filter,
} from 'lucide-react';
import {
  GeneratedReportItem,
  ScheduledReportItem,
  SavedReportItem,
} from '@/types/reports';

interface ReportsTableProps {
  recentReports: GeneratedReportItem[];
  scheduledReports: ScheduledReportItem[];
  savedReports: SavedReportItem[];
  onDownloadReport: (report: GeneratedReportItem) => void;
  onRunScheduledNow: (report: ScheduledReportItem) => void;
  onRunSavedReport: (report: SavedReportItem) => void;
}

export function ReportsTable({
  recentReports,
  scheduledReports,
  savedReports,
  onDownloadReport,
  onRunScheduledNow,
  onRunSavedReport,
}: ReportsTableProps) {
  const [activeTab, setActiveTab] = useState<'recent' | 'scheduled' | 'saved'>(
    'recent'
  );
  const [activeMenuId, setActiveMenuId] = useState<string | null>(null);

  return (
    <div className="bg-white rounded-2xl border border-slate-200/80 shadow-xs overflow-hidden flex flex-col">
      {/* Tabs Header */}
      <div className="flex items-center gap-6 px-6 pt-4 border-b border-slate-100">
        <button
          onClick={() => setActiveTab('recent')}
          className={`pb-3 text-xs font-semibold tracking-tight transition-all relative ${
            activeTab === 'recent'
              ? 'text-[#008a90] border-b-2 border-[#008a90]'
              : 'text-slate-500 hover:text-slate-800'
          }`}
        >
          Recent Reports
        </button>
        <button
          onClick={() => setActiveTab('scheduled')}
          className={`pb-3 text-xs font-semibold tracking-tight transition-all relative ${
            activeTab === 'scheduled'
              ? 'text-[#008a90] border-b-2 border-[#008a90]'
              : 'text-slate-500 hover:text-slate-800'
          }`}
        >
          Scheduled Reports
        </button>
        <button
          onClick={() => setActiveTab('saved')}
          className={`pb-3 text-xs font-semibold tracking-tight transition-all relative ${
            activeTab === 'saved'
              ? 'text-[#008a90] border-b-2 border-[#008a90]'
              : 'text-slate-500 hover:text-slate-800'
          }`}
        >
          Saved Reports
        </button>
      </div>

      {/* Table Content */}
      <div className="overflow-x-auto">
        {activeTab === 'recent' && (
          <table className="w-full text-xs text-left">
            <thead className="bg-slate-50/80 text-slate-500 font-semibold border-b border-slate-100">
              <tr>
                <th className="py-3 px-6">Report Name</th>
                <th className="py-3 px-4">Category</th>
                <th className="py-3 px-4">Generated On</th>
                <th className="py-3 px-4">Generated By</th>
                <th className="py-3 px-4">Status</th>
                <th className="py-3 px-6 text-right">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {recentReports.map((report) => (
                <tr
                  key={report.id}
                  className="hover:bg-slate-50/60 transition-colors"
                >
                  <td className="py-3.5 px-6 font-semibold text-slate-800">
                    <div className="flex items-center gap-2">
                      <FileText className="w-3.5 h-3.5 text-slate-400" />
                      <span>{report.name}</span>
                    </div>
                  </td>
                  <td className="py-3.5 px-4 text-slate-600 font-medium">
                    {report.category}
                  </td>
                  <td className="py-3.5 px-4 text-slate-500 font-mono text-[11px]">
                    {report.generatedOn}
                  </td>
                  <td className="py-3.5 px-4 text-slate-600">
                    {report.generatedBy}
                  </td>
                  <td className="py-3.5 px-4">
                    <span className="inline-flex items-center gap-1.5 text-emerald-600 font-medium">
                      <span className="w-2 h-2 rounded-full bg-emerald-500" />
                      {report.status}
                    </span>
                  </td>
                  <td className="py-3.5 px-6 text-right">
                    <div className="inline-flex items-center gap-2">
                      <button
                        onClick={() => onDownloadReport(report)}
                        className="text-[#008a90] hover:text-[#00747a] font-semibold text-xs hover:underline cursor-pointer"
                      >
                        Download
                      </button>
                      <button
                        onClick={() =>
                          setActiveMenuId(
                            activeMenuId === report.id ? null : report.id
                          )
                        }
                        className="text-slate-400 hover:text-slate-700 p-1 rounded-md"
                        title="More options"
                      >
                        <MoreHorizontal className="w-4 h-4" />
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}

        {activeTab === 'scheduled' && (
          <table className="w-full text-xs text-left">
            <thead className="bg-slate-50/80 text-slate-500 font-semibold border-b border-slate-100">
              <tr>
                <th className="py-3 px-6">Scheduled Task</th>
                <th className="py-3 px-4">Frequency</th>
                <th className="py-3 px-4">Recipients</th>
                <th className="py-3 px-4">Next Run</th>
                <th className="py-3 px-4">Status</th>
                <th className="py-3 px-6 text-right">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {scheduledReports.map((sch) => (
                <tr
                  key={sch.id}
                  className="hover:bg-slate-50/60 transition-colors"
                >
                  <td className="py-3.5 px-6 font-semibold text-slate-800">
                    {sch.name}
                  </td>
                  <td className="py-3.5 px-4">
                    <span className="px-2 py-0.5 rounded-full text-[10px] font-semibold bg-teal-50 text-[#008a90] border border-teal-200/60">
                      {sch.frequency}
                    </span>
                  </td>
                  <td className="py-3.5 px-4 text-slate-500 max-w-[180px] truncate">
                    {sch.recipients}
                  </td>
                  <td className="py-3.5 px-4 text-slate-600 font-mono text-[11px]">
                    {sch.nextRun}
                  </td>
                  <td className="py-3.5 px-4">
                    <span className="inline-flex items-center gap-1.5 text-emerald-600 font-medium">
                      <span className="w-2 h-2 rounded-full bg-emerald-500" />
                      {sch.status}
                    </span>
                  </td>
                  <td className="py-3.5 px-6 text-right">
                    <button
                      onClick={() => onRunScheduledNow(sch)}
                      className="px-2.5 py-1 text-xs font-semibold text-[#008a90] bg-teal-50 hover:bg-teal-100 rounded-lg transition-colors inline-flex items-center gap-1"
                    >
                      <Play className="w-3 h-3 fill-current" />
                      Run Now
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}

        {activeTab === 'saved' && (
          <table className="w-full text-xs text-left">
            <thead className="bg-slate-50/80 text-slate-500 font-semibold border-b border-slate-100">
              <tr>
                <th className="py-3 px-6">Report Title</th>
                <th className="py-3 px-4">Category</th>
                <th className="py-3 px-4">Filter Criteria</th>
                <th className="py-3 px-4">Created On</th>
                <th className="py-3 px-6 text-right">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {savedReports.map((sav) => (
                <tr
                  key={sav.id}
                  className="hover:bg-slate-50/60 transition-colors"
                >
                  <td className="py-3.5 px-6 font-semibold text-slate-800">
                    {sav.name}
                  </td>
                  <td className="py-3.5 px-4 text-slate-600 font-medium">
                    {sav.category}
                  </td>
                  <td className="py-3.5 px-4 text-slate-500 max-w-[220px] truncate">
                    {sav.filtersSummary}
                  </td>
                  <td className="py-3.5 px-4 text-slate-500 font-mono text-[11px]">
                    {sav.createdOn}
                  </td>
                  <td className="py-3.5 px-6 text-right">
                    <button
                      onClick={() => onRunSavedReport(sav)}
                      className="px-2.5 py-1 text-xs font-semibold text-white bg-[#008a90] hover:bg-[#00747a] rounded-lg transition-colors inline-flex items-center gap-1"
                    >
                      <Play className="w-3 h-3 fill-current" />
                      Generate
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>
    </div>
  );
}

